    /** 根据当前日期获取每日语录 */
    fun getDailyQuote(): String {
        val today = LocalDate.now()
        // 使用一年的第几天作为索引，确保每天都不一样
        val index = (today.dayOfYear - 1) % quotes.size
        return quotes[index]
    }
